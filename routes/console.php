/*
 * Create the admin account or reset its password. The password is typed at a hidden prompt,
 * so it never ends up in code, git, or shell history.
 */
Artisan::command('admin:password {email : Admin email, e.g. admin@leedefusion.com} {--name=Leede Fusion Admin}', function () {
    $email = strtolower(trim($this->argument('email')));
    if (! filter_var($email, FILTER_VALIDATE_EMAIL)) {
        $this->error('That is not a valid email address.');

        return 1;
    }

    $password = (string) $this->secret('New admin password (hidden)');
    if (strlen($password) < 10) {
        $this->error('Use at least 10 characters.');

        return 1;
    }
    if ($password !== (string) $this->secret('Repeat the password')) {
        $this->error('Passwords do not match.');

        return 1;
    }
    $plain = strtolower(preg_replace('/[^a-z0-9]/i', '', $password));
    if (str_contains($plain, 'leede') && strlen($plain) < 16 && ! $this->confirm('This password contains the brand/domain name and is easy to guess. Use it anyway?', false)) {
        return 1;
    }

    $user = \App\Models\User::query()->firstOrNew(['email' => $email]);
    $user->name = $user->name ?: $this->option('name');
    $user->password = $password; // hashed by the User model cast
    $user->forceFill(['is_admin' => true])->save();

    // Sign out every existing session/API token for this account.
    $user->tokens()->delete();

    $this->info(($user->wasRecentlyCreated ? 'Admin created: ' : 'Password updated for: ').$email);

    return 0;
})->purpose('Create an admin or reset an admin password via a hidden prompt');

