/*
 * Node/Vite is not available on every machine. Layouts fall back to public/css + public/js
 * when there is no Vite build, so mirror the sources there (Alpine itself comes from the CDN).
 */
Artisan::command('assets:fallback', function () {
    foreach (['storefront.css', 'admin-theme.css'] as $css) {
        copy(resource_path("css/{$css}"), public_path("css/{$css}"));
    }

    // app.css imports storefront.css and adds a few global rules (x-cloak etc.); append those too.
    $extra = preg_replace('/^@import .*$/m', '', file_get_contents(resource_path('css/app.css')));
    file_put_contents(public_path('css/storefront.css'), $extra, FILE_APPEND);

    $js = file_get_contents(resource_path('js/app.js'));
    $js = preg_replace('/^import Alpine from .alpinejs.;\R/m', '', $js);
    $js = preg_replace('/^window\.Alpine = Alpine;\R?|^Alpine\.start\(\);\R?/m', '', $js);

    if (! is_dir(public_path('js'))) {
        mkdir(public_path('js'), 0755, true);
    }
    file_put_contents(public_path('js/app.js'), "/* Generated by `php artisan assets:fallback` from resources/js/app.js. Do not edit. */\n".$js);

    $this->info('Fallback assets written to public/css and public/js.');
})->purpose('Copy CSS/JS into public/ for running without a Vite build');

/*
 * Large camera JPGs in public/ make pages slow. This writes a resized WebP next to each one
 * (originals are kept) and points stored image paths in the database at the WebP version.
 */
Artisan::command('images:optimize {--max=1600 : Longest edge in pixels} {--quality=78}', function () {
    $max = (int) $this->option('max');
    $quality = (int) $this->option('quality');
    $renamed = [];

    foreach (glob(public_path('*.{jpg,jpeg,png,JPG,JPEG,PNG}'), GLOB_BRACE) as $path) {
        if (filesize($path) < 200 * 1024 || str_contains(basename($path), ' ') || basename($path) === 'Logo.png') {
            continue; // small already, odd filename, or the logo (kept as PNG)
        }

        $image = @imagecreatefromstring(file_get_contents($path));
        if (! $image) {
            $this->warn('Skipped (unreadable): '.basename($path));
            continue;
        }

        [$w, $h] = [imagesx($image), imagesy($image)];
        $scale = min(1, $max / max($w, $h));
        if ($scale < 1) {
            $resized = imagescale($image, (int) round($w * $scale), (int) round($h * $scale), IMG_BICUBIC);
            imagedestroy($image);
            $image = $resized;
        }

        $target = preg_replace('/\.(jpe?g|png)$/i', '.webp', $path);
        imagewebp($image, $target, $quality);
        imagedestroy($image);

        $renamed['/'.basename($path)] = '/'.basename($target);
        $this->line(sprintf('%-28s %6d KB → %5d KB', basename($path), filesize($path) / 1024, filesize($target) / 1024));
    }

    // Repoint stored paths (product images & galleries, category covers, journal covers, studio options, settings).
    $columns = [
        'products' => ['image', 'images'],
        'categories' => ['image'],
        'posts' => ['cover_image', 'body'],
        'design_options' => ['image'],
        'settings' => ['value'],
    ];
    foreach ($columns as $table => $cols) {
        foreach ($cols as $col) {
            foreach ($renamed as $from => $to) {
                // JSON columns store "/" as "\/", so replace both spellings.
                foreach ([[$from, $to], [str_replace('/', '\\/', $from), str_replace('/', '\\/', $to)]] as [$a, $b]) {
                    \Illuminate\Support\Facades\DB::table($table)->where($col, 'like', '%'.$a.'%')
                        ->update([$col => \Illuminate\Support\Facades\DB::raw('REPLACE('.$col.', '.\Illuminate\Support\Facades\DB::getPdo()->quote($a).', '.\Illuminate\Support\Facades\DB::getPdo()->quote($b).')')]);
                }
            }
        }
    }

    \Illuminate\Support\Facades\Cache::forget(\App\Models\Setting::CACHE_KEY);
    $this->info(count($renamed).' images optimized; database paths updated.');
})->purpose('Create compressed WebP copies of large public images and use them');
